"""Regenerates compose.yaml with the setup scripts embedded, so TrueNAS needs just one paste.
Run: python3 build_compose.py"""
from pathlib import Path

here = Path(__file__).parent


def embed(name):
    # Compose treats $ as a variable; $$ is a literal dollar sign.
    text = (here / name).read_text().replace("$", "$$")
    return "".join("      " + line if line.strip() else "\n" for line in text.splitlines(keepends=True))


compose = """# Matrix server with WhatsApp and Discord bridges, for the Seance and Conclave iPhone apps.
# TrueNAS: Apps -> Discover Apps -> (three dots) Install via YAML -> name it matrix -> paste this file.
# Edit the lines marked CHANGE before saving. Generated by build_compose.py.
#
# Everything sets itself up on the first start: the server, your account, and both bridges.
# Messages are stored unencrypted on the NAS: keep port 8790 on Tailscale only.

x-common: &common
  restart: unless-stopped
  networks: [matrix]

x-env: &env
  # CHANGE (optional): your Matrix server name. It becomes part of your address (@you:this-name)
  # and can never be changed later. It doesn't need to be a real domain.
  SERVER_NAME: keepwatch.home
  # CHANGE: the username and password you'll sign in to Seance and Conclave with.
  MATRIX_USER: CHANGE-ME-username
  MATRIX_PASSWORD: CHANGE-ME-to-a-long-random-password
  # Largest single file (photo, video, document) you can send or receive. There's no paid plan:
  # this is your own server, so raise it as far as your NAS's disk allows.
  MAX_UPLOAD: 2G
  TZ: Europe/London

services:
  synapse:
    <<: *common
    image: matrixdotorg/synapse:v1.165.0
    container_name: matrix-synapse
    entrypoint: ["/bin/sh", "/setup/synapse.sh"]
    configs:
      - source: synapse_sh
        target: /setup/synapse.sh
      - source: patch_synapse
        target: /setup/patch_synapse.py
    volumes:
      - synapse-data:/data
      - appservices:/appservices
    environment:
      <<: *env
    ports:
      # The apps connect to http://<your NAS's Tailscale IP>:8790
      - "8790:8008"

  whatsapp:
    <<: *common
    image: dock.mau.dev/mautrix/whatsapp:v26.10
    container_name: matrix-whatsapp
    entrypoint: ["/bin/sh", "/setup/bridge.sh"]
    configs:
      - source: bridge_sh
        target: /setup/bridge.sh
    volumes:
      - whatsapp-data:/data
      - appservices:/appservices
    environment:
      <<: *env
      BRIDGE: whatsapp
      PORT: "29318"

  discord:
    <<: *common
    image: dock.mau.dev/mautrix/discord:v0.7.7
    container_name: matrix-discord
    entrypoint: ["/bin/sh", "/setup/bridge.sh"]
    configs:
      - source: bridge_sh
        target: /setup/bridge.sh
    volumes:
      - discord-data:/data
      - appservices:/appservices
    environment:
      <<: *env
      BRIDGE: discord
      PORT: "29334"

networks:
  matrix:

volumes:
  synapse-data:
  whatsapp-data:
  discord-data:
  appservices:

configs:
  synapse_sh:
    content: |
""" + embed("synapse.sh") + """  patch_synapse:
    content: |
""" + embed("patch_synapse.py") + """  bridge_sh:
    content: |
""" + embed("bridge.sh")
(here / "compose.yaml").write_text(compose)
print("wrote compose.yaml")
